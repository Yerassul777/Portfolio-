// Builds the home page's map of Kazakhstan drawn in dots from
// assets/geo/kazakhstan.geo.json (Natural Earth, public domain):
// - public/images/kz-map-<hash>.svg, the dots. A file, not inline: it is not
//   repeated in every page's HTML and React payload, and the service worker
//   keeps it; the hash in the name means a new map is never served stale.
// - lib/kz-map.ts: that file's name, the proportions and the cities.
// Run after changing the grid or the cities: node scripts/make-kz-map.mjs
import crypto from "node:crypto"
import fs from "node:fs"

/** Dots across the widest part of the country. */
const COLUMNS = 64
/** The map's width in SVG units; the height follows from the shape. */
const WIDTH = 1000
/** A dot's diameter, as a share of the grid's step. */
const DOT = 0.42

// The main cities: where the lights are. [id, longitude, latitude, major];
// the capital and the largest city get a bigger light.
const CITIES = [
  ["astana", 71.43, 51.13, true],
  ["almaty", 76.89, 43.24, true],
  ["shymkent", 69.59, 42.32],
  ["karaganda", 73.1, 49.8],
  ["aktobe", 57.17, 50.28],
  ["atyrau", 51.92, 47.11],
  ["aktau", 51.2, 43.65],
  ["oskemen", 82.61, 49.95],
  ["pavlodar", 76.95, 52.29],
  ["kostanay", 63.63, 53.21],
  ["oral", 51.37, 51.23],
  ["kyzylorda", 65.51, 44.85],
  ["taraz", 71.37, 42.9],
  ["petropavl", 69.15, 54.87],
]

const outline = JSON.parse(fs.readFileSync(new URL("../assets/geo/kazakhstan.geo.json", import.meta.url), "utf8"))
const ring = outline.geometry.coordinates[0]
const lons = ring.map(([lon]) => lon)
const lats = ring.map(([, lat]) => lat)
const [west, east, south, north] = [Math.min(...lons), Math.max(...lons), Math.min(...lats), Math.max(...lats)]
// Equirectangular, squeezed by the cosine of the middle latitude: true shape at this size.
const squeeze = Math.cos((((north + south) / 2) * Math.PI) / 180)
const scale = WIDTH / ((east - west) * squeeze)
const HEIGHT = Math.round((north - south) * scale)
const project = (lon, lat) => [(lon - west) * squeeze * scale, (north - lat) * scale]
const polygon = ring.map(([lon, lat]) => project(lon, lat))

function inside([x, y]) {
  let hit = false
  for (let i = 0, j = polygon.length - 1; i < polygon.length; j = i++) {
    const [xi, yi] = polygon[i]
    const [xj, yj] = polygon[j]
    if (yi > y !== yj > y && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) hit = !hit
  }
  return hit
}

// A hexagonal grid (every other row shifted by half a step) reads as a
// texture rather than a table.
const step = WIDTH / COLUMNS
const rowStep = step * Math.sin(Math.PI / 3)
const dots = []
for (let row = 0; row * rowStep <= HEIGHT; row++) {
  const y = row * rowStep + rowStep / 2
  for (let x = row % 2 ? step : step / 2; x < WIDTH; x += step) {
    if (inside([x, y])) dots.push(`M${x.toFixed(1)} ${y.toFixed(1)}h0`)
  }
}

// Zero-length segments with round caps: one path draws every dot.
const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${WIDTH} ${HEIGHT}"><path fill="none" stroke="#fff" stroke-linecap="round" stroke-width="${(step * DOT).toFixed(2)}" d="${dots.join("")}"/></svg>\n`
const name = `kz-map-${crypto.createHash("sha256").update(svg).digest("hex").slice(0, 8)}.svg`
const images = new URL("../public/images/", import.meta.url)
for (const old of fs.readdirSync(images).filter((file) => /^kz-map-[0-9a-f]{8}\.svg$/.test(file))) fs.rmSync(new URL(old, images))
fs.writeFileSync(new URL(name, images), svg)

const cities = CITIES.map(([id, lon, lat, major]) => {
  const [x, y] = project(lon, lat)
  return { id, x: +((x / WIDTH) * 100).toFixed(2), y: +((y / HEIGHT) * 100).toFixed(2), major: Boolean(major) }
})

const source = `// Generated by scripts/make-kz-map.mjs from assets/geo/kazakhstan.geo.json
// (Natural Earth, public domain). Do not edit by hand: run the script.

/** Kazakhstan in dots: the drawing, its proportions and the main cities. */
export const KZ_MAP = {
  src: "/images/${name}",
  width: ${WIDTH},
  height: ${HEIGHT},
  /** Positions in % of the map's width and height; major: the capital and the largest city. */
  cities: ${JSON.stringify(cities)},
} as const
`
fs.writeFileSync(new URL("../lib/kz-map.ts", import.meta.url), source)
console.log(`public/images/${name}: ${dots.length} dots, ${WIDTH}×${HEIGHT}, ${(svg.length / 1024).toFixed(1)} KB`)
